import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:integration_test/integration_test.dart';
import 'package:path/path.dart' as path;
import 'package:sqflite/sqflite.dart';
import 'package:zhi_ai/local_courses.dart';
import 'package:zhi_ai/local_exam_page.dart';

void main() {
  IntegrationTestWidgetsFlutterBinding.ensureInitialized();
  testWidgets('local paper preserves draft and submits only once', (tester) async {
    if (!const bool.fromEnvironment('INTEGRATION_TEST_ISOLATED')) throw TestFailure('Use isolated emulator');
    await deleteDatabase(path.join(await getDatabasesPath(), 'local_courses.db'));
    final store = await LocalCourses.open();
    await store.add('课程');
    final id = (await store.list()).single['id'] as int;
    await store.addQuestion(id, '第一题', '1', '');
    await store.addQuestion(id, '第二题', '2', '');
    await store.close();
    await tester.pumpWidget(MaterialApp(home: LocalExamListPage(courseId: id)));
    for (var i = 0; i < 80 && find.text('手动组合已有题目').evaluate().isEmpty; i++) await tester.pump(const Duration(milliseconds: 200));
    await tester.tap(find.text('手动组合已有题目'));
    await tester.pumpAndSettle();
    await tester.tap(find.text('第一题'));
    await tester.tap(find.text('第二题'));
    await tester.tap(find.text('创建'));
    for (var i = 0; i < 80 && (find.byType(AlertDialog).evaluate().isNotEmpty || find.text('本地自测卷').evaluate().isEmpty); i++) await tester.pump(const Duration(milliseconds: 200));
    await tester.tap(find.text('本地自测卷'));
    await tester.pump(const Duration(seconds: 2));
    await tester.enterText(find.byType(TextField).at(0), '2');
    await tester.enterText(find.byType(TextField).at(1), '1');
    await tester.pageBack();
    await tester.pumpAndSettle();
    expect(find.text('答案尚未保存'), findsOneWidget);
    await tester.tap(find.text('继续作答'));
    await tester.pumpAndSettle();
    expect(tester.widget<TextField>(find.byType(TextField).at(0)).controller!.text, '2');
    await tester.ensureVisible(find.text('保存草稿'));
    await tester.pump(const Duration(milliseconds: 300));
    await tester.tap(find.text('保存草稿'));
    await tester.pump(const Duration(seconds: 2));
    await tester.pageBack();
    await tester.pump(const Duration(seconds: 2));
    await tester.tap(find.text('本地自测卷'));
    await tester.pump(const Duration(seconds: 2));
    expect(tester.widget<TextField>(find.byType(TextField).at(0)).controller!.text, '2');
    expect(tester.widget<TextField>(find.byType(TextField).at(1)).controller!.text, '1');
    await tester.ensureVisible(find.text('提交试卷'));
    await tester.pump(const Duration(milliseconds: 300));
    await tester.tap(find.text('提交试卷'));
    await tester.pumpAndSettle();
    await tester.tap(find.text('提交').last);
    await tester.pump(const Duration(seconds: 3));
    expect(find.textContaining('答对 2 / 2 题'), findsOneWidget);
    final check = await LocalCourses.open();
    expect(await check.db.query('local_attempts'), hasLength(2));
    await check.close();
    expect(tester.takeException(), isNull);
  });
}
